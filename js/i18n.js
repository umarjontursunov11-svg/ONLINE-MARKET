let currentLang = localStorage.getItem('sm_lang') || 'uz';

function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.uz;
  return dict[key] || TRANSLATIONS.uz[key] || key;
}

function setLanguage(lang) {
  if (lang !== 'uz' && lang !== 'ru') lang = 'uz';
  currentLang = lang;
  localStorage.setItem('sm_lang', lang);
  document.documentElement.setAttribute('lang', lang);

  // Update switcher buttons active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Apply translations to all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text) {
      el.innerHTML = text;
    }
  });

  // Apply placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = t(key);
    if (text) {
      el.placeholder = text;
    }
  });

  // Apply titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const text = t(key);
    if (text) {
      el.title = text;
    }
  });

  // Re-render dynamic components in the new language if app is loaded
  if (typeof renderCategoryShowcase === 'function') renderCategoryShowcase();
  if (typeof renderDiscountedProducts === 'function') renderDiscountedProducts();
  if (typeof renderCategoryTabs === 'function') renderCategoryTabs();
  if (typeof renderProducts === 'function') renderProducts();
  if (typeof store !== 'undefined' && typeof store.renderCart === 'function') store.renderCart();
  if (typeof currentOfferData !== 'undefined' && currentOfferData && typeof renderCommercialOfferHTML === 'function') {
    renderCommercialOfferHTML();
  }
}

// Convert numbers to Russian words for Commercial Offer
function numberToRussianWords(num) {
  if (!num || num === 0) return "Ноль сум 00 тийин";
  
  const ones = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];
  const onesFemale = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];
  const teens = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"];
  const tens = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"];
  const hundreds = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"];

  function morph(n, f1, f2, f5) {
    n = Math.abs(n) % 100;
    const n1 = n % 10;
    if (n > 10 && n < 20) return f5;
    if (n1 > 1 && n1 < 5) return f2;
    if (n1 === 1) return f1;
    return f5;
  }

  function convertGroup(n, isFemale = false) {
    let s = "";
    const h = Math.floor(n / 100);
    const rem = n % 100;
    const t = Math.floor(rem / 10);
    const o = rem % 10;

    if (h > 0) s += hundreds[h] + " ";
    if (t === 1) {
      s += teens[o] + " ";
    } else {
      if (t > 1) s += tens[t] + " ";
      if (o > 0) s += (isFemale ? onesFemale[o] : ones[o]) + " ";
    }
    return s.trim();
  }

  let words = "";
  const billion = Math.floor(num / 1000000000);
  const million = Math.floor((num % 1000000000) / 1000000);
  const thousand = Math.floor((num % 1000000) / 1000);
  const remainder = Math.floor(num % 1000);

  if (billion > 0) {
    words += convertGroup(billion, false) + " " + morph(billion, "миллиард", "миллиарда", "миллиардов") + " ";
  }
  if (million > 0) {
    words += convertGroup(million, false) + " " + morph(million, "миллион", "миллиона", "миллионов") + " ";
  }
  if (thousand > 0) {
    words += convertGroup(thousand, true) + " " + morph(thousand, "тысяча", "тысячи", "тысяч") + " ";
  }
  if (remainder > 0) {
    words += convertGroup(remainder, false) + " ";
  }

  words = words.trim();
  if (words) {
    const sumWord = morph(Math.floor(num), "сум", "сума", "сумов");
    return words.charAt(0).toUpperCase() + words.slice(1) + " " + sumWord + " 00 тийин";
  }
  return "Ноль сум 00 тийин";
}

